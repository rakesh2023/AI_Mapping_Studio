/* =========================================================================
   upcoming-features.js  (Help ▸ Upcoming Features)
   A simple roadmap table. Add / edit items in the UPCOMING list below — the
   Sr# is generated automatically from the row order.
   ========================================================================= */

const UPCOMING = [
  { title: "Multi-language (i18n) support",
    description: "English + Japanese interface, with AI-generated mapping text following the selected UI language." },
  { title: "Lookup value-level AI mapping",
    description: "Turn each lookup's expected values into a reviewable source-code → target-code grid, generated by AI and editable per row." },
  { title: "Mapping approval workflow",
    description: "Route generated mappings through review and sign-off, with an audit trail of who approved what and when." },
  { title: "Scheduled schema re-extraction",
    description: "Automatically re-read source and target schemas on a schedule and highlight changes since the last extract." },
  { title: "Schema change notifications",
    description: "Send a notification whenever a schema file changes — e.g. columns added, removed, or renamed since the last extract." },
];

document.addEventListener("DOMContentLoaded", async () => {
  await initShell("upcoming-features.html");
  renderUpcoming();
});

function renderUpcoming(){
  const body = document.getElementById("upcomingBody");
  if(!body) return;
  if(!UPCOMING.length){
    body.innerHTML = '<tr><td colspan="3" class="text-xs text-muted-2">No upcoming features listed yet.</td></tr>';
    return;
  }
  body.innerHTML = UPCOMING.map((f, i) =>
    '<tr>' +
      '<td class="mono">' + (i + 1) + '</td>' +
      '<td style="font-weight:600;">' + escapeHtml(f.title || "") + '</td>' +
      '<td class="wrap">' + escapeHtml(f.description || "") + '</td>' +
    '</tr>').join("");
}
